export function mergeWithDefaultTexts(rawTexts?: Partial<SiteTexts> | null): SiteTexts {
  if (!rawTexts) return DEFAULT_TEXTS;
  return {
    nav: { ...DEFAULT_TEXTS.nav, ...(rawTexts.nav || {}) },
    hero: { ...DEFAULT_TEXTS.hero, ...(rawTexts.hero || {}) },
    calendar: { ...DEFAULT_TEXTS.calendar, ...(rawTexts.calendar || {}) },
    roster: { ...DEFAULT_TEXTS.roster, ...(rawTexts.roster || {}) },
    record: { ...DEFAULT_TEXTS.record, ...(rawTexts.record || {}) },
    stats: {
      ...DEFAULT_TEXTS.stats,
      ...(rawTexts.stats || {}),
      mapStats:
        Array.isArray(rawTexts.stats?.mapStats) && rawTexts.stats.mapStats.length > 0
          ? rawTexts.stats.mapStats
          : DEFAULT_TEXTS.stats.mapStats,
    },
    gallery: { ...DEFAULT_TEXTS.gallery, ...(rawTexts.gallery || {}) },
    info: {
      ...DEFAULT_TEXTS.info,
      ...(rawTexts.info || {}),
      rules:
        Array.isArray(rawTexts.info?.rules) && rawTexts.info.rules.length > 0
          ? rawTexts.info.rules
          : DEFAULT_TEXTS.info.rules,
    },
    footer: { ...DEFAULT_TEXTS.footer, ...(rawTexts.footer || {}) },
  };
}
